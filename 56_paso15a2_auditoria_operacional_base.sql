-- ============================================================
-- 5. HELPER INTERNO DE REGISTRO
-- ============================================================

create or replace function
public.__drito_registrar_auditoria_operacion(
  p_comercio_id uuid,
  p_modulo text,
  p_accion text,
  p_entidad_tipo text,
  p_entidad_id text default null,
  p_referencia text default null,
  p_detalle jsonb default '{}'::jsonb,
  p_realizado_por uuid default null
)
returns bigint
language plpgsql
security definer
set search_path = public
as $function$
declare
  v_id bigint;

  v_modulo text;
  v_accion text;
  v_entidad_tipo text;

  v_actor uuid;
begin

  if p_comercio_id is null then
    raise exception
      'El comercio es obligatorio para registrar auditoría';
  end if;


  if not exists (
    select 1
    from public.comercios c
    where c.id = p_comercio_id
  ) then
    raise exception
      'El comercio indicado no existe';
  end if;


  v_modulo :=
    nullif(trim(coalesce(p_modulo, '')), '');

  v_accion :=
    nullif(trim(coalesce(p_accion, '')), '');

  v_entidad_tipo :=
    nullif(trim(coalesce(p_entidad_tipo, '')), '');


  if v_modulo is null then
    raise exception
      'El módulo de auditoría es obligatorio';
  end if;


  if v_accion is null then
    raise exception
      'La acción de auditoría es obligatoria';
  end if;


  if v_entidad_tipo is null then
    raise exception
      'El tipo de entidad auditada es obligatorio';
  end if;


  if p_detalle is not null
     and jsonb_typeof(p_detalle) <> 'object' then
    raise exception
      'El detalle de auditoría debe ser un objeto JSON';
  end if;


  v_actor :=
    coalesce(
      p_realizado_por,
      auth.uid()
    );


  insert into public.auditoria_operaciones (
    comercio_id,
    modulo,
    accion,
    entidad_tipo,
    entidad_id,
    referencia,
    detalle,
    realizado_por
  )
  values (
    p_comercio_id,
    v_modulo,
    v_accion,
    v_entidad_tipo,
    nullif(trim(coalesce(p_entidad_id, '')), ''),
    nullif(trim(coalesce(p_referencia, '')), ''),
    coalesce(p_detalle, '{}'::jsonb),
    v_actor
  )
  returning id
  into v_id;


  return v_id;

end;
$function$;


-- Helper exclusivamente interno.
-- El frontend no puede invocarlo directamente.

revoke all on function
public.__drito_registrar_auditoria_operacion(
  uuid,
  text,
  text,
  text,
  text,
  text,
  jsonb,
  uuid
)
from public, anon, authenticated;


-- ============================================================
-- 6. RPC DE CONSULTA
-- ============================================================

create or replace function
public.obtener_auditoria_operaciones(
  p_comercio_id uuid,
  p_fecha_desde date default null,
  p_fecha_hasta date default null,
  p_modulo text default null,
  p_accion text default null,
  p_entidad_tipo text default null,
  p_busqueda text default null,
  p_limite integer default 200,
  p_offset integer default 0
)
returns table (
  id bigint,
  comercio_id uuid,
  modulo text,
  accion text,
  entidad_tipo text,
  entidad_id text,
  referencia text,
  detalle jsonb,
  realizado_por uuid,
  created_at timestamptz
)
language plpgsql
stable
security definer
set search_path = public
as $function$
declare
  v_limite integer;
  v_offset integer;

  v_busqueda text;
begin

  perform public.exigir_permiso_comercio(
    p_comercio_id,
    'auditoria.ver'
  );


  v_limite :=
    least(
      greatest(coalesce(p_limite, 200), 1),
      1000
    );


  v_offset :=
    greatest(
      coalesce(p_offset, 0),
      0
    );


  v_busqueda :=
    nullif(
      trim(coalesce(p_busqueda, '')),
      ''
    );


  return query
  select
    ao.id,
    ao.comercio_id,
    ao.modulo,
    ao.accion,
    ao.entidad_tipo,
    ao.entidad_id,
    ao.referencia,
    ao.detalle,
    ao.realizado_por,
    ao.created_at
  from public.auditoria_operaciones ao
  where ao.comercio_id = p_comercio_id

    and (
      p_fecha_desde is null
      or ao.created_at >= p_fecha_desde::timestamptz
    )

    and (
      p_fecha_hasta is null
      or ao.created_at
        < (p_fecha_hasta + 1)::timestamptz
    )

    and (
      nullif(trim(coalesce(p_modulo, '')), '') is null
      or ao.modulo = trim(p_modulo)
    )

    and (
      nullif(trim(coalesce(p_accion, '')), '') is null
      or ao.accion = trim(p_accion)
    )

    and (
      nullif(trim(coalesce(p_entidad_tipo, '')), '') is null
      or ao.entidad_tipo = trim(p_entidad_tipo)
    )

    and (
      v_busqueda is null

      or ao.referencia ilike '%' || v_busqueda || '%'

      or ao.entidad_id ilike '%' || v_busqueda || '%'

      or ao.modulo ilike '%' || v_busqueda || '%'

      or ao.accion ilike '%' || v_busqueda || '%'

      or ao.entidad_tipo ilike '%' || v_busqueda || '%'

      or ao.detalle::text ilike '%' || v_busqueda || '%'
    )

  order by ao.created_at desc, ao.id desc

  limit v_limite
  offset v_offset;

end;
$function$;


revoke all on function
public.obtener_auditoria_operaciones(
  uuid,
  date,
  date,
  text,
  text,
  text,
  text,
  integer,
  integer
)
from public, anon;


grant execute on function
public.obtener_auditoria_operaciones(
  uuid,
  date,
  date,
  text,
  text,
  text,
  text,
  integer,
  integer
)
to authenticated;


