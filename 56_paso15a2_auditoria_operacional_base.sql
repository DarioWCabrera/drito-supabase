select jsonb_build_object(

  'tabla',
    to_regclass(
      'public.auditoria_operaciones'
    ) is not null,

  'permiso_auditoria_ver',
    exists (
      select 1
      from public.permisos_sistema ps
      where ps.codigo = 'auditoria.ver'
        and ps.activo = true
    ),

  'admin_con_permiso',
    exists (
      select 1
      from public.roles_permisos rp
      where rp.rol = 'admin'
        and rp.permiso_codigo = 'auditoria.ver'
        and rp.permitido = true
    ),

  'helper_interno',
    to_regprocedure(
      'public.__drito_registrar_auditoria_operacion(uuid,text,text,text,text,text,jsonb,uuid)'
    ) is not null,

  'rpc_consulta',
    to_regprocedure(
      'public.obtener_auditoria_operaciones(uuid,date,date,text,text,text,text,integer,integer)'
    ) is not null,

  'rls_activo',
    (
      select c.relrowsecurity
      from pg_class c
      join pg_namespace n
        on n.oid = c.relnamespace
      where n.nspname = 'public'
        and c.relname = 'auditoria_operaciones'
    ),

  'authenticated_insert_directo',
    has_table_privilege(
      'authenticated',
      'public.auditoria_operaciones',
      'INSERT'
    ),

  'authenticated_update_directo',
    has_table_privilege(
      'authenticated',
      'public.auditoria_operaciones',
      'UPDATE'
    ),

  'authenticated_delete_directo',
    has_table_privilege(
      'authenticated',
      'public.auditoria_operaciones',
