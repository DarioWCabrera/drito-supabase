-- ============================================================
-- 2. TABLA DE AUDITORÍA OPERACIONAL
-- ============================================================

create table if not exists
public.auditoria_operaciones (
  id bigint
    generated by default as identity
    primary key,

  comercio_id uuid not null
    references public.comercios(id)
    on delete restrict,

  modulo text not null,

  accion text not null,

  entidad_tipo text not null,

  entidad_id text,

  referencia text,

  detalle jsonb not null
    default '{}'::jsonb,

  realizado_por uuid
    references auth.users(id)
    on delete set null,

  created_at timestamptz not null
    default now(),

  constraint auditoria_operaciones_modulo_no_vacio
    check (length(trim(modulo)) > 0),

  constraint auditoria_operaciones_accion_no_vacia
    check (length(trim(accion)) > 0),

  constraint auditoria_operaciones_entidad_no_vacia
    check (length(trim(entidad_tipo)) > 0),

  constraint auditoria_operaciones_detalle_objeto
    check (jsonb_typeof(detalle) = 'object')
);


